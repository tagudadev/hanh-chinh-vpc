// Helper to construct sample records using central late logic
function createInitialRecord(
  id: string,
  employeeCode: string,
  employeeId: string,
  date: string,
  arrivalTime: string,
  notes?: string,
  priorNoticeStatus: 'reported' | 'unreported' | 'unverified' = 'unverified',
  noticeTime?: string,
  noticeMethod?: 'zalo' | 'phone' | 'direct' | 'email' | 'other'
): ArrivalRecord {
  const evalResult = evaluateArrivalLate(arrivalTime, DEFAULT_LATE_THRESHOLD);
  return {
    id,
    employeeId,
    employeeCode,
    date,
    arrivalTime,
    isLate: evalResult.isLate,
    lateSeconds: evalResult.lateSeconds,
    priorNoticeStatus,
    noticeTime,
    noticeMethod,
    notes,
    createdAt: `${date}T${arrivalTime}Z`,
    createdBy: 'Hệ thống Quản lý VPC',
  };
}

